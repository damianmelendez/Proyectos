    private int buscarCliente(String nit){
    Cliente Clien = clientesBD.consultarCliente(nit);
    int pocicion = -1;
        if (Clien != null) {
            jtfNombre.setText(Clien.getNombre());
            jtfApellido.setText(Clien.getApellido());
            jtfNit.setText(Clien.getNit());
            jtfDireccion.setText(Clien.getDireccion());
            if (Clien.isGenero()) {
                jrbFemenino.setSelected(true);
            } else {
                jrbMasculino.setSelected(false);
            }
            pocicion = 0;
        } else {
            System.out.println("no encontrado");
        }
        return pocicion;
    }
    
