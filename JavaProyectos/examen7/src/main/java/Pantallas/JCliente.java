    private void jbGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbGuardarActionPerformed
        // TODO add your handling code here:
        Cliente Client = new Cliente();
        Client.setNombre(jtfNombre.getText());
        Client.setApellido(jtfApellido.getText());
        Client.setNit(jtfNit.getText());
        Client.setDireccion(jtfDireccion.getText());
        if (jrbFemenino.isSelected()) {
            Client.setGenero(true);
        } else {
            Client.setGenero(false);
        }
        if (this.nit.isEmpty()) {
            if (!clientesBD.insertarDato(Client)) {
                JOptionPane.showMessageDialog(this,"no guardado","Guardar", JOptionPane.INFORMATION_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this,"Guardado","Guardar", JOptionPane.INFORMATION_MESSAGE);
            }
        } else {
            if (!clientesBD.actualizarDato(Client, nit)) {
                JOptionPane.showMessageDialog(this,"no actualizado","Guardar", JOptionPane.INFORMATION_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this,"Actualizado","Guardar", JOptionPane.INFORMATION_MESSAGE);
            }
        }
    }//GEN-LAST:event_jbGuardarActionPerformed

