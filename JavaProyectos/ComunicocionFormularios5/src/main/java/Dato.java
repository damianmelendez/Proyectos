public class Dato {
    private String Valor;

    public Dato() {
    }

    public Dato(String Valor) {
        this.Valor = Valor;
    }

    public String getValor() {
        return Valor;
    }

    public void setValor(String Valor) {
        this.Valor = Valor;
    }

    @Override
    public String toString() {
        return "Dato{" + "Valor=" + Valor + '}';
    }
    
    
    
}
